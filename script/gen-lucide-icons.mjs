#!/usr/bin/env node
// Regenerates plugin/ui/core/LucideIcons.h from the lucide-react package the
// web UI depends on. The icon set is whatever ui/src/components/icons.tsx
// imports, so the native UI and the web UI can never drift on glyph shapes,
// plus NATIVE_ONLY: glyphs for screens that exist only natively (the search
// browser's filter button) and so have no web import to mirror.
//
//   node script/gen-lucide-icons.mjs
//
// Each icon becomes one SVG string with lucide's default attributes
// (24×24 viewBox, 2px round stroke, `currentColor` → white, tinted at draw
// time by Icons::draw).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const NATIVE_ONLY = ['ListFilter'];

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsTsx = readFileSync(join(root, 'ui/src/components/icons.tsx'), 'utf8');
const lucideDir = join(root, 'ui/node_modules/lucide-react/dist/esm/icons');
const out = join(root, 'plugin/ui/core/LucideIcons.h');

const webNames = [...iconsTsx.matchAll(/^\s+(\w+) as L\w+,$/gm)].map((m) => m[1]);
if (webNames.length === 0) throw new Error('no lucide imports found in icons.tsx');
const names = [...new Set([...webNames, ...NATIVE_ONLY])].sort();

// Lucide's own toKebabCase: a letter→digit boundary also splits (Redo2 → redo-2).
const kebab = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/([a-zA-Z])(\d)/g, '$1-$2')
    .toLowerCase();

const attrs = (o) =>
  Object.entries(o)
    .filter(([k]) => k !== 'key')
    .map(([k, v]) => ` ${k}="${v}"`)
    .join('');

// Alias modules (PlusCircle → circle-plus) only re-export the component;
// follow the re-export to the module that owns the node list.
const loadIconNode = async (file) => {
  const alias = readFileSync(file, 'utf8').match(/^export \{ default \} from '\.\/(.+)';$/m);
  if (alias) return loadIconNode(join(lucideDir, alias[1]));
  return (await import(pathToFileURL(file).href)).__iconNode;
};

const entries = [];
for (const name of names) {
  const node = await loadIconNode(join(lucideDir, `${kebab(name)}.mjs`));
  const body = node.map(([tag, a]) => `<${tag}${attrs(a)}/>`).join('');
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#ffffff" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
  entries.push({ name, svg });
}

const header = `// GENERATED by script/gen-lucide-icons.mjs from lucide-react; do not edit.
// Icon set = ui/src/components/icons.tsx imports + the script's NATIVE_ONLY
// list. Lucide is ISC licensed.
#pragma once

namespace t3k::ui {

enum class Icon {
${entries.map((e) => `  ${e.name},`).join('\n')}
};

inline constexpr int kIconCount = ${entries.length};

inline const char* lucideSvg(Icon icon) {
  switch (icon) {
${entries.map((e) => `    case Icon::${e.name}:\n      return R"svg(${e.svg})svg";`).join('\n')}
  }
  return "";
}

}  // namespace t3k::ui
`;

writeFileSync(out, header);
console.log(`wrote ${entries.length} icons to ${out}`);
